#!/usr/bin/env python3
# Swiftboard web port: generates Swift `_PresentationStrings` from Telegram's en Localizable.strings with the API the
# upstream ObjC generator (build-system/GenerateStrings) exposes to Swift: plain keys are String properties,
# pluralized keys (Key_0/_1/_2/_3_10/_many/_any) are `func Key(_ value: Int32) -> String`, keys with %@/%d are
# `func Key(_ _0: String|Int, ...) -> _FormattedString` (string + argument ranges). Dots become underscores.
#   gen-strings.py Localizable.strings Out.swift [source globs: only keys used there]
import re, sys
src, out = sys.argv[1], sys.argv[2]
# optional: only keys whose identifier appears in these Swift sources (keeps the module small)
import glob
used = None
if len(sys.argv) > 3:
    words = set()
    for pat in sys.argv[3:]:
        for f in glob.glob(pat, recursive=True):
            words |= set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', open(f, encoding='utf-8', errors='ignore').read()))
    used = words
text = open(src, encoding='utf-8').read()
pairs = re.findall(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', text, re.M)
arg_re = re.compile(r'%((\d+)\$)?([@d])')
def args(v):
    res, implicit = [], 0
    for m in arg_re.finditer(v):
        if m.group(2) is None: idx = implicit; implicit += 1
        else: idx = int(m.group(2))
        res.append((idx, m.group(3)))
    return res
plural = re.compile(r'^(.*?)_(0|1|2|3_10|many|any)$')
entries = {}
order = []
for k, v in pairs:
    m = plural.match(k)
    if m:
        name = m.group(1)
        e = entries.setdefault(name, {'plural': {}, 'value': None})
        if name not in order: order.append(name)
        e['plural'][m.group(2)] = v
    else:
        if k in entries and entries[k]['value'] is not None: continue
        e = entries.setdefault(k, {'plural': {}, 'value': None})
        if k not in order: order.append(k)
        e['value'] = v
def ident(k): return re.sub(r'[^A-Za-z0-9_]', '_', k)
def lit(v): return '"' + re.sub(r'\\U([0-9a-fA-F]{4})', r'\\u{\1}', v).replace('\r', '').replace('\n', '\\n') + '"'
o = ['// Generated by demos/telegram/tools/gen-strings.py from Telegram en.lproj/Localizable.strings. Do not edit.',
     'import Foundation', '', 'extension _PresentationStrings {']
seen = set()
for k in order:
    e = entries[k]; name = ident(k)
    if name in seen or not re.match(r'[A-Za-z_]', name): continue
    if used is not None and name not in used: continue
    seen.add(name)
    if e['plural']:
        forms = ', '.join(f'"{f}": {lit(v)}' for f, v in e['plural'].items())
        o.append(f'    public func {name}(_ value: Int32) -> String {{ _plural(value, [{forms}]) }}')
    else:
        v = e['value']; a = args(v)
        if not a:
            o.append(f'    public var {name}: String {{ {lit(v)} }}')
        else:
            n = max(i for i, _ in a) + 1
            kinds = {i: kd for i, kd in a}
            params = ', '.join(f'_ _{i}: ' + ('Int' if kinds.get(i) == 'd' else 'String') for i in range(n))
            vals = ', '.join(f'"\\(_{i})"' for i in range(n))
            o.append(f'    public func {name}({params}) -> _FormattedString {{ _format({lit(v)}, [{vals}]) }}')
o.append('}')
open(out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')
print(f'{len(seen)} keys')
