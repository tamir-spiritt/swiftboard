#!/usr/bin/env python3
# Swiftboard (MIT): rebuilds ICU's packaged common data (icudtNN_dat) with only what an English-locale UI needs, and
# emits a C file defining the same symbol. Linked before lib_FoundationICU.a, it replaces the 34 MB data object.
#   icu-trim.py icu_packaged_data.cpp.obj out.c [--list kept.txt]
# Kept: core property/normalization files, root/en/en_US resources in every tree, supplemental tables. Dropped:
# legacy charset converters, other locales, transliteration, break-iterator dictionaries, unicode names.
import struct, sys, re
src, out = sys.argv[1], sys.argv[2]
b = open(src, 'rb').read()
start = b.find(b'CmnD') - 12
hs = struct.unpack_from('<H', b, start)[0]
toc = start + hs
n = struct.unpack_from('<I', b, toc)[0]
ents = [struct.unpack_from('<II', b, toc + 4 + 8 * k) for k in range(n)]
def name(off): s = toc + off; return b[s:b.index(b'\0', s)].decode()
# end of the last item: the object's data payload size isn't marked; use the largest gap heuristic (items are 16-aligned)
items = []
for k, (no, do) in enumerate(ents):
    end = ents[k + 1][1] if k + 1 < n else None
    items.append((name(no), toc + do, end and toc + end))
last_name, last_start, _ = items[-1]
# last item: read its own size from its header (ICU data items start with MappedData + UDataInfo; size unknown) -> keep to end of TOC data
items[-1] = (last_name, last_start, last_start + 16)  # dropped below unless needed
LOCALES = {'root', 'en', 'en_US', 'en_001', 'pool', 'res_index'}
TOP_RES = {'likelySubtags', 'supplementalData', 'metaZones', 'timezoneTypes', 'windowsZones', 'zoneinfo64', 'numberingSystems',
           'plurals', 'dayPeriods', 'grammaticalFeatures', 'units', 'keyTypeData', 'icuver', 'icustd', 'currencyNumericCodes',
           'genderList', 'langInfo', 'pool', 'res_index', 'root', 'en', 'en_US', 'en_001', 'personNameFormat'}
def keep(nm):
    p = nm.split('/', 1)[1]
    base, ext = (p.rsplit('.', 1) + [''])[:2]
    if '/' in p:
        tree, leaf = p.split('/', 1)
        stem = leaf.rsplit('.', 1)[0]
        if tree == 'translit': return False
        if tree == 'brkitr': return stem in LOCALES or (ext == 'brk' and stem in ('char', 'word', 'line', 'sent', 'title'))
        if tree == 'coll': return stem in LOCALES or ext == 'icu'
        return stem in LOCALES
    if ext == 'cnv': return False
    if ext == 'res': return base in TOP_RES
    if base == 'unames': return False
    return True
kept = [it for it in items if keep(it[0]) and it[2]]
# rebuild: header, TOC (count, entries), names, aligned data
names = b''.join(nm.encode() + b'\0' for nm, _, _ in kept)
toc_size = 4 + 8 * len(kept)
data_off = (toc_size + len(names) + 15) & ~15
entries, blobs, cur = [], [], data_off
for (nm, s, e), name_off in zip(kept, [0] + list(__import__('itertools').accumulate(len(x[0].encode()) + 1 for x in kept))[:-1]):
    blob = b[s:e]
    entries.append(struct.pack('<II', toc_size + name_off, cur))
    pad = (-len(blob)) & 15
    blobs.append(blob + b'\0' * pad); cur += len(blob) + pad
pkg = b[start:toc] + struct.pack('<I', len(kept)) + b''.join(entries) + names
pkg += b'\0' * (hs + data_off - len(pkg)) + b''.join(blobs)
sym = 'icudt' + re.search(r'icudt(\d+)', items[0][0]).group(1) + '_dat'
with open(out, 'w') as f:
    f.write(f'// Generated by platform/tools/icu-trim.py: trimmed ICU common data ({len(kept)} of {n} items).\n')
    f.write(f'__attribute__((aligned(16))) const unsigned char {sym}[{len(pkg)}] = {{\n')
    for i in range(0, len(pkg), 32): f.write(','.join(str(x) for x in pkg[i:i + 32]) + ',\n')
    f.write('};\n')
if '--list' in sys.argv: open(sys.argv[sys.argv.index('--list') + 1], 'w').write('\n'.join(x[0] for x in kept))
print(f'{sym}: kept {len(kept)}/{n} items, {len(pkg)} bytes (was {len(b)})')
